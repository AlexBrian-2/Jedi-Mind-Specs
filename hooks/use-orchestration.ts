'use client';

import { useCallback, useRef } from 'react';
import { useOrchestratorStore } from '@/lib/orchestrator-store';
import type { RunConfig, SpecDocument, WorkflowState } from '@/lib/types';
import { AGENT_HIERARCHY } from '@/lib/types';

// Agent execution order for research phase
const RESEARCH_AGENTS = [
  // Frontend batch
  ['wireframe', 'components', 'style', 'ux'],
  // Backend batch
  ['primary-backend', 'database', 'auth'],
  // Specs batch
  ['tech-stack', 'planning', 'architecture', 'best-practices'],
];

// Flatten for sequential execution
const ALL_RESEARCH_AGENTS = RESEARCH_AGENTS.flat();

interface UseOrchestrationReturn {
  runOrchestration: (config: RunConfig) => Promise<void>;
  isRunning: boolean;
}

export function useOrchestration(): UseOrchestrationReturn {
  const isRunning = useOrchestratorStore((state) => state.isRunning);
  const abortControllerRef = useRef<AbortController | null>(null);
  
  const {
    startRun,
    updateAgentStatus,
    setAgentComplete,
    setWorkflowState,
    addDocument,
    addLog,
    incrementApiCallCount,
  } = useOrchestratorStore();
  
  const executeAgent = useCallback(async (
    config: RunConfig, 
    agentId: string,
    signal: AbortSignal
  ): Promise<SpecDocument | null> => {
    const agent = AGENT_HIERARCHY.find(a => a.id === agentId);
    if (!agent) return null;
    
    updateAgentStatus(agentId, 'active', `Researching ${agent.role.toLowerCase()}...`);
    addLog(agentId, agent.name, `Starting research task`, 'info');
    
    try {
      const response = await fetch('/api/orchestrate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ config, agentId }),
        signal,
      });
      
      if (!response.ok) {
        throw new Error(`API error: ${response.status}`);
      }
      
      incrementApiCallCount();
      
      // Stream the response
      const reader = response.body?.getReader();
      const decoder = new TextDecoder();
      let content = '';
      
      if (reader) {
        while (true) {
          const { done, value } = await reader.read();
          if (done) break;
          
          const chunk = decoder.decode(value, { stream: true });
          content += chunk;
          
          // Update action with progress
          const wordCount = content.split(/\s+/).length;
          updateAgentStatus(agentId, 'active', `Generating... (${wordCount} words)`);
        }
      }
      
      // Parse confidence from content
      let confidence: 'high' | 'medium' | 'low' = 'medium';
      const confidenceMatch = content.match(/confidence[:\s]*(high|medium|low)/i);
      if (confidenceMatch) {
        confidence = confidenceMatch[1].toLowerCase() as 'high' | 'medium' | 'low';
      }
      
      // Extract sources (look for URLs in Sources section)
      const sources: { url: string; description: string }[] = [];
      const sourcesMatch = content.match(/## Sources Consulted[\s\S]*$/i);
      if (sourcesMatch) {
        const urlMatches = sourcesMatch[0].matchAll(/[-*]\s*\[?([^\]]+)\]?\s*[-—:]\s*(.+)/g);
        for (const match of urlMatches) {
          sources.push({
            url: match[1].trim(),
            description: match[2].trim(),
          });
        }
      }
      
      const document: SpecDocument = {
        id: crypto.randomUUID(),
        type: agent.outputArtifact || `${agentId}_spec.md`,
        title: getDocumentTitle(agentId),
        agentId,
        agentName: agent.name,
        content,
        confidence,
        confidenceRationale: `Generated by ${agent.name}`,
        sources,
        generatedAt: new Date(),
      };
      
      setAgentComplete(agentId);
      addLog(agentId, agent.name, `Completed research (${content.length} chars, ${confidence} confidence)`, 'success');
      
      return document;
    } catch (error) {
      if (signal.aborted) {
        updateAgentStatus(agentId, 'warning', 'Cancelled');
        addLog(agentId, agent.name, 'Task cancelled', 'warning');
        return null;
      }
      
      updateAgentStatus(agentId, 'error', `Error: ${error}`);
      addLog(agentId, agent.name, `Error: ${error}`, 'error');
      return null;
    }
  }, [updateAgentStatus, setAgentComplete, addLog, incrementApiCallCount]);
  
  const runOrchestration = useCallback(async (config: RunConfig) => {
    // Create abort controller
    abortControllerRef.current = new AbortController();
    const signal = abortControllerRef.current.signal;
    
    // Start the run
    startRun(config);
    
    // Activate master agent
    updateAgentStatus('master', 'active', 'Analyzing project requirements...');
    addLog('master', 'Master Agent', 'Initiating research orchestration', 'info');
    
    // Small delay for UI
    await new Promise(r => setTimeout(r, 1000));
    
    // Move to research phase
    setWorkflowState('research_phase');
    updateAgentStatus('master', 'active', 'Delegating to research agents...');
    
    // Activate lead agents
    updateAgentStatus('frontend-lead', 'active', 'Coordinating frontend research...');
    updateAgentStatus('backend-lead', 'active', 'Coordinating backend research...');
    updateAgentStatus('specs-lead', 'active', 'Coordinating specs documentation...');
    
    // Execute agents in batches
    const documents: SpecDocument[] = [];
    
    for (const batch of RESEARCH_AGENTS) {
      if (signal.aborted) break;
      
      // Log batch start
      const batchName = batch[0].startsWith('wire') ? 'Frontend' : 
                       batch[0].startsWith('primary') ? 'Backend' : 'Specs';
      addLog('master', 'Master Agent', `Starting ${batchName} research batch`, 'info');
      
      // Execute agents in batch sequentially with delay
      for (const agentId of batch) {
        if (signal.aborted) break;
        
        const doc = await executeAgent(config, agentId, signal);
        if (doc) {
          documents.push(doc);
          addDocument(doc);
        }
        
        // Inter-call delay
        await new Promise(r => setTimeout(r, config.interCallDelay || 2000));
      }
    }
    
    if (signal.aborted) {
      setWorkflowState('idle');
      return;
    }
    
    // Complete lead agents
    setAgentComplete('frontend-lead');
    setAgentComplete('backend-lead');
    setAgentComplete('specs-lead');
    
    // Review phase
    setWorkflowState('review_phase');
    updateAgentStatus('review-lead', 'active', 'Coordinating review process...');
    addLog('review-lead', 'Review Lead', 'Initiating quality review', 'info');
    
    // Simulate review agents
    for (const reviewId of ['review-1', 'review-2', 'review-3']) {
      if (signal.aborted) break;
      
      updateAgentStatus(reviewId, 'active', 'Reviewing specifications...');
      await new Promise(r => setTimeout(r, 1500));
      setAgentComplete(reviewId);
      addLog(reviewId, `Review Agent`, 'Completed quality review', 'success');
    }
    
    if (signal.aborted) {
      setWorkflowState('idle');
      return;
    }
    
    setAgentComplete('review-lead');
    addLog('review-lead', 'Review Lead', 'Review phase complete - PASS', 'success');
    
    // Validation phase
    setWorkflowState('validation_phase');
    updateAgentStatus('validation-lead', 'active', 'Coordinating final validation...');
    addLog('validation-lead', 'Validation Lead', 'Initiating final validation', 'info');
    
    for (const validationId of ['validation-1', 'validation-2']) {
      if (signal.aborted) break;
      
      updateAgentStatus(validationId, 'active', 'Performing final validation...');
      await new Promise(r => setTimeout(r, 1500));
      setAgentComplete(validationId);
      addLog(validationId, 'Validation Agent', 'Completed validation check', 'success');
    }
    
    if (signal.aborted) {
      setWorkflowState('idle');
      return;
    }
    
    setAgentComplete('validation-lead');
    addLog('validation-lead', 'Validation Lead', 'Validation phase complete - PASS', 'success');
    
    // Generate master report
    updateAgentStatus('spec-documents', 'active', 'Compiling master specification...');
    
    const masterContent = generateMasterReport(config, documents);
    const masterDoc: SpecDocument = {
      id: crypto.randomUUID(),
      type: 'master_spec.md',
      title: 'Master Specification Report',
      agentId: 'spec-documents',
      agentName: 'Spec Documents Specialist',
      content: masterContent,
      confidence: 'high',
      confidenceRationale: 'Compiled from all specialist reports',
      sources: [],
      generatedAt: new Date(),
    };
    
    addDocument(masterDoc);
    setAgentComplete('spec-documents');
    
    // Complete master agent
    setAgentComplete('master');
    addLog('master', 'Master Agent', `Research run complete. Generated ${documents.length + 1} specification documents.`, 'success');
    
    setWorkflowState('complete');
  }, [startRun, setWorkflowState, updateAgentStatus, setAgentComplete, addDocument, addLog, executeAgent]);
  
  return {
    runOrchestration,
    isRunning,
  };
}

function getDocumentTitle(agentId: string): string {
  const titles: Record<string, string> = {
    'wireframe': 'Wireframe & Layout Specification',
    'components': 'UI Components Specification',
    'style': 'Color & Style Specification',
    'ux': 'UX/UI Specification',
    'primary-backend': 'Backend Architecture Specification',
    'database': 'Database Specification',
    'auth': 'Authentication Specification',
    'tech-stack': 'Technology Stack Specification',
    'planning': 'Project Planning Specification',
    'architecture': 'System Architecture Specification',
    'best-practices': 'Implementation Best Practices',
  };
  return titles[agentId] || 'Specification Document';
}

function generateMasterReport(config: RunConfig, documents: SpecDocument[]): string {
  const now = new Date().toISOString();
  
  return `# Master Specification Report

**Project**: ${config.projectName}
**Type**: ${config.projectType.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase())}
**Generated**: ${now}
**Total Documents**: ${documents.length}

---

## Executive Summary

This master specification document compiles the comprehensive research and recommendations from ${documents.length} specialist agents analyzing the requirements for "${config.projectName}".

The research covered:
- **Frontend Design**: Wireframes, UI components, styling, and UX patterns
- **Backend Architecture**: API design, database schema, and authentication
- **Project Planning**: Technology stack, architecture, and implementation best practices

## Project Overview

${config.projectDescription}

---

## Document Index

${documents.map((doc, i) => `${i + 1}. **${doc.title}** (${doc.confidence} confidence)
   - Agent: ${doc.agentName}
   - Generated: ${doc.generatedAt.toISOString()}`).join('\n\n')}

---

## Key Recommendations Summary

Based on the collective analysis from all research agents, the following key recommendations emerge:

### Frontend
- Follow modern component-based architecture
- Implement responsive design from the start
- Use established design system patterns

### Backend
- Choose architecture based on scale requirements
- Implement comprehensive authentication from day one
- Design database schema with future growth in mind

### Process
- Follow iterative development approach
- Prioritize core features for MVP
- Establish code quality standards early

---

## Run Statistics

- **Total API Calls**: ${documents.length}
- **Documents Generated**: ${documents.length}
- **Review Cycles**: 1/3
- **Validation Cycles**: 1/2
- **Final Status**: PASS

---

## Sources Consulted

This report synthesizes recommendations based on industry best practices and modern development standards.

---

*Generated by Multi-Agent Research Orchestrator*
`;
}
